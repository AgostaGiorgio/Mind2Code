from datetime import datetime
from enum import Enum
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator


def _to_camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(part.capitalize() for part in parts[1:])


class ProjectStatus(str, Enum):
    ERROR = "ERROR"
    REQUIREMENTS_RUNNING = "REQUIREMENTS_RUNNING"
    REQUIREMENTS_DONE = "REQUIREMENTS_DONE"
    CODE_RUNNING = "CODE_RUNNING"
    CODE_DONE = "CODE_DONE"
    TEST_RUNNING = "TEST_RUNNING"
    TEST_DONE = "TEST_DONE"
    REVIEW_RUNNING = "REVIEW_RUNNING"
    REVIEW_DONE = "REVIEW_DONE"
    RETROSPECTIVE_RUNNING = "RETROSPECTIVE_RUNNING"
    RETROSPECTIVE_DONE = "RETROSPECTIVE_DONE"


class Project(BaseModel):
    model_config = ConfigDict(
        alias_generator=_to_camel,
        populate_by_name=True,
        from_attributes=True,
    )

    id: UUID = Field(..., description="Unique identifier generated by the database")
    name: str = Field(..., description="Project name")
    github_url: str = Field(..., description="Project GitHub repository URL")
    completion_percentage: int = Field(
        ..., ge=0, le=100, description="Completion percentage from 0 to 100"
    )
    finalization_percentage: int = Field(
        0, ge=0, le=100, description="Finalization progress from 0 to 100"
    )
    auto: bool = Field(
        False,
        description="Whether every pipeline step should run automatically, one after another",
    )
    status: ProjectStatus | None = Field(
        None,
        description="Current pipeline status, written by the external workflow",
    )
    final_repo_url: str | None = Field(
        None, description="URL of the finalized (real) repository, once released"
    )
    finalize_error: str | None = Field(
        None, description="Last finalization error, if any"
    )
    created_at: datetime = Field(..., description="Creation timestamp")
    updated_at: datetime = Field(..., description="Last update timestamp")


class ProgressUpdateRequest(BaseModel):
    model_config = ConfigDict(
        alias_generator=_to_camel,
        populate_by_name=True,
    )

    completion_percentage: int = Field(
        ..., ge=0, le=100, description="New completion percentage from 0 to 100"
    )

    @field_validator("completion_percentage")
    @classmethod
    def _validate_percentage(cls, value: int) -> int:
        if not 0 <= value <= 100:
            raise ValueError("completionPercentage must be between 0 and 100")
        return value


class ProjectNameUpdateRequest(BaseModel):
    model_config = ConfigDict(
        alias_generator=_to_camel,
        populate_by_name=True,
    )

    name: str = Field(..., min_length=1, max_length=200, description="New project name")

    @field_validator("name")
    @classmethod
    def _validate_name(cls, value: str) -> str:
        stripped = value.strip()
        if not stripped:
            raise ValueError("name must not be blank")
        return stripped


class ProjectCreateRequest(BaseModel):
    model_config = ConfigDict(
        alias_generator=_to_camel,
        populate_by_name=True,
    )

    user_input: str = Field(
        ...,
        min_length=1,
        max_length=100_000,
        description="Free-form description of what the user wants to build",
    )
    auto: bool = Field(
        False,
        description="Whether every pipeline step should run automatically, one after another",
    )

    @field_validator("user_input")
    @classmethod
    def _validate_user_input(cls, value: str) -> str:
        stripped = value.strip()
        if not stripped:
            raise ValueError("userInput must not be blank")
        return stripped


class ProgressEvent(BaseModel):
    model_config = ConfigDict(
        alias_generator=_to_camel,
        populate_by_name=True,
    )

    project_id: UUID = Field(..., description="UUID of the updated project")
    completion_percentage: int = Field(..., description="Updated completion percentage")
    status: ProjectStatus | None = Field(
        None, description="Current pipeline status"
    )


class FinalizationEvent(BaseModel):
    model_config = ConfigDict(
        alias_generator=_to_camel,
        populate_by_name=True,
    )

    project_id: UUID = Field(..., description="UUID of the project")
    finalization_percentage: int = Field(..., description="Finalization progress 0-100")
    final_repo_url: str | None = Field(None, description="Finalized repository URL")
    finalize_error: str | None = Field(None, description="Last finalization error")


class ProjectDetail(Project):
    """A project with its Markdown documents.

    The documents are populated in the ``projects`` table by the external
    service and returned only by the single-project endpoint (the list endpoint
    stays lean).
    """

    user_input: str | None = Field(None, description="Free-form user input document")
    requirements: str | None = Field(None, description="Requirements / spec document")
    code_summary: str | None = Field(None, description="Code summary document")
    test_summary: str | None = Field(None, description="Test summary document")
    final_review: str | None = Field(None, description="Final review document")
    retrospective: str | None = Field(
        None, description="Retrospective report generated at the end of finalization"
    )
